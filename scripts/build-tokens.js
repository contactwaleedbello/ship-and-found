#!/usr/bin/env node
'use strict';

/*
 * Convert tokens/tokens.json into CSS custom properties.
 *
 * No dependencies. Every token value comes from the JSON; this script only
 * chooses names, units and the CSS structure.
 */

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const INPUT_FILE = path.join(ROOT, 'tokens', 'tokens.json');
const OUTPUT_DIR = path.join(ROOT, 'styles', 'tokens');

const COLLECTION = {
  primitives: 'Primitives',
  colours: 'colour roles',
  typography: 'typography',
  spacing: 'spacing roles',
  shape: 'shape roles',
  shadow: 'shadow roles',
};

const HEADER =
  '/* Generated by scripts/build-tokens.js from tokens/tokens.json. Do not edit by hand. */';

const warnings = [];
const skipped = [];

function fail(message) {
  console.error(`\nBUILD FAILED: ${message}`);
  process.exit(1);
}

function warn(message) {
  warnings.push(message);
}

function noteSkipped(message) {
  skipped.push(message);
}

function dash(name) {
  return name.replace(/\//g, '-');
}

function variableKey(collection, variable) {
  return `${collection}\u0000${variable}`;
}

function parseAlias(value) {
  if (typeof value !== 'string') return null;
  const match = /^\{([^:}]+):([^}]+)\}$/.exec(value.trim());
  return match
    ? { collection: match[1], variable: match[2] }
    : null;
}

function expectNumber(value, where) {
  if (typeof value !== 'number' || !Number.isFinite(value)) {
    fail(`${where}: expected a finite number, got ${JSON.stringify(value)}.`);
  }
  return value;
}

function expectHex(value, where) {
  if (typeof value !== 'string' || !/^#[0-9a-fA-F]{6}$/.test(value)) {
    fail(`${where}: expected a #RRGGBB colour, got ${JSON.stringify(value)}.`);
  }
  return value;
}

function hexToRgb(value, where) {
  const match = /^#([0-9a-fA-F]{6})$/.exec(expectHex(value, where));
  const number = Number.parseInt(match[1], 16);
  return {
    r: (number >> 16) & 0xff,
    g: (number >> 8) & 0xff,
    b: number & 0xff,
  };
}

/* ------------------------------------------------------------------ */
/* Read and index the JSON                                            */
/* ------------------------------------------------------------------ */

let data;
try {
  data = JSON.parse(fs.readFileSync(INPUT_FILE, 'utf8'));
} catch (error) {
  fail(
    `Could not read or parse ${path.relative(ROOT, INPUT_FILE)}: ${error.message}`,
  );
}

if (!data.variables || !Array.isArray(data.variables.collections)) {
  fail('tokens.json is missing variables.collections[].');
}
if (!Array.isArray(data.textStyles)) {
  fail('tokens.json is missing textStyles[].');
}
if (!Array.isArray(data.effectStyles)) {
  fail('tokens.json is missing effectStyles[].');
}

const collections = new Map();
const variables = new Map();

for (const collection of data.variables.collections) {
  if (!collection || typeof collection.name !== 'string') {
    fail('Found a variable collection with no name.');
  }
  if (collections.has(collection.name)) {
    fail(`Duplicate collection "${collection.name}".`);
  }
  if (!Array.isArray(collection.modes) || collection.modes.length === 0) {
    fail(`Collection "${collection.name}" has no modes.`);
  }
  if (!Array.isArray(collection.variables)) {
    fail(`Collection "${collection.name}" has no variables array.`);
  }

  const variableMap = new Map();
  for (const variable of collection.variables) {
    if (!variable || typeof variable.name !== 'string') {
      fail(`Collection "${collection.name}" contains a variable with no name.`);
    }
    if (variableMap.has(variable.name)) {
      fail(
        `Duplicate variable "${variable.name}" in collection "${collection.name}".`,
      );
    }
    variableMap.set(variable.name, variable);
    variables.set(variableKey(collection.name, variable.name), variable);
  }

  collections.set(collection.name, {
    definition: collection,
    variableMap,
  });
}

function getCollection(name) {
  const entry = collections.get(name);
  if (!entry) {
    fail(
      `Expected collection "${name}" was not found in ${path.relative(
        ROOT,
        INPUT_FILE,
      )}.`,
    );
  }
  return entry;
}

function getSingleMode(name) {
  const entry = getCollection(name);
  if (entry.definition.modes.length !== 1) {
    fail(
      `Collection "${name}" has ${entry.definition.modes.length} modes (${entry.definition.modes.join(
        ', ',
      )}); this build expects exactly one.`,
    );
  }
  return { entry, mode: entry.definition.modes[0] };
}

/* Check every alias in the file, even aliases we do not emit ourselves. */
function validateAlias(value, where) {
  if (typeof value !== 'string' || !value.trim().startsWith('{')) return;
  const alias = parseAlias(value);
  if (!alias) {
    fail(`Malformed alias ${JSON.stringify(value)} at ${where}.`);
  }
  if (!variables.has(variableKey(alias.collection, alias.variable))) {
    fail(
      `Alias ${JSON.stringify(value)} at ${where} points at missing variable "${
        alias.variable
      }" in collection "${alias.collection}".`,
    );
  }
}

for (const [collectionName, entry] of collections) {
  for (const variable of entry.variableMap.values()) {
    if (variable.type !== 'COLOR' && variable.type !== 'FLOAT') {
      fail(
        `Variable "${variable.name}" in "${collectionName}" has unsupported type ${JSON.stringify(
          variable.type,
        )}.`,
      );
    }
    if (!variable.values || typeof variable.values !== 'object') {
      fail(`Variable "${variable.name}" in "${collectionName}" has no values.`);
    }
    for (const mode of entry.definition.modes) {
      if (variable.values[mode] === undefined) {
        fail(
          `Variable "${variable.name}" in "${collectionName}" has no value for mode "${mode}".`,
        );
      }
    }
    for (const [mode, value] of Object.entries(variable.values)) {
      validateAlias(value, `${collectionName}/${variable.name} [${mode}]`);
    }
  }
}

for (const style of data.textStyles) {
  if (!style || typeof style.name !== 'string') {
    fail('Found a text style with no name.');
  }
  for (const [property, value] of Object.entries(style.boundVariables || {})) {
    validateAlias(value, `textStyles/${style.name}.boundVariables.${property}`);
  }
}

for (const style of data.effectStyles) {
  if (!style || typeof style.name !== 'string') {
    fail('Found an effect style with no name.');
  }
  for (const [property, value] of Object.entries(style.boundVariables || {})) {
    validateAlias(
      value,
      `effectStyles/${style.name}.boundVariables.${property}`,
    );
  }
}

/* ------------------------------------------------------------------ */
/* Name and value mapping                                             */
/* ------------------------------------------------------------------ */

function cssVariableName(collectionName, variableName) {
  if (collectionName === COLLECTION.primitives) {
    return `--primitive-${dash(variableName)}`;
  }
  if (collectionName === COLLECTION.colours) {
    return `--color-${dash(variableName)}`;
  }
  if (collectionName === COLLECTION.spacing) {
    if (variableName.startsWith('breakpoint/')) return null;
    return `--spacing-${dash(variableName)}`;
  }
  if (collectionName === COLLECTION.shape) {
    if (variableName.startsWith('radius/')) {
      return `--radius-${dash(variableName.slice('radius/'.length))}`;
    }
    if (variableName.startsWith('border/width/')) {
      return `--border-width-${dash(
        variableName.slice('border/width/'.length),
      )}`;
    }
    return null;
  }
  if (collectionName === COLLECTION.typography) {
    const match = /^(.+)\/(size|line-height|letter-spacing|weight)$/.exec(
      variableName,
    );
    if (!match) return null;
    return `--type-${dash(match[1])}-${match[2]}`;
  }
  return null;
}

function aliasToCss(value, where) {
  const alias = parseAlias(value);
  if (!alias) return null;

  if (!variables.has(variableKey(alias.collection, alias.variable))) {
    fail(
      `Alias ${JSON.stringify(value)} at ${where} points at missing variable "${
        alias.variable
      }" in collection "${alias.collection}".`,
    );
  }

  const name = cssVariableName(alias.collection, alias.variable);
  if (!name) {
    fail(
      `Alias ${JSON.stringify(value)} at ${where} points at "${
        alias.collection
      }/${alias.variable}", which is not emitted as a CSS custom property.`,
    );
  }
  return `var(${name})`;
}

/* ------------------------------------------------------------------ */
/* Primitives                                                         */
/* ------------------------------------------------------------------ */

const { entry: primitivesEntry, mode: primitiveMode } = getSingleMode(
  COLLECTION.primitives,
);

const primitiveLines = [];
for (const variable of primitivesEntry.variableMap.values()) {
  const where = `Primitives/${variable.name} [${primitiveMode}]`;
  const value = variable.values[primitiveMode];

  let cssValue;
  const alias = aliasToCss(value, where);

  if (alias) {
    cssValue = alias;
  } else if (variable.type === 'COLOR') {
    cssValue = expectHex(value, where);
  } else if (variable.type === 'FLOAT') {
    const number = expectNumber(value, where);
    /*
     * space/*, radius/* and border/* are lengths. elevation/* is a level
     * number, so it stays unitless.
     */
    const unit = variable.name.startsWith('elevation/') ? '' : 'px';
    cssValue = `${number}${unit}`;
  } else {
    fail(
      `${where}: unsupported variable type ${JSON.stringify(variable.type)}.`,
    );
  }

  primitiveLines.push(
    `  ${cssVariableName(COLLECTION.primitives, variable.name)}: ${cssValue};`,
  );
}

const primitivesCss = `${HEADER}\n\n:root {\n${primitiveLines.join('\n')}\n}\n`;

/* ------------------------------------------------------------------ */
/* Colour roles                                                       */
/* ------------------------------------------------------------------ */

const colourEntry = getCollection(COLLECTION.colours);
const colourModes = colourEntry.definition.modes;

if (
  colourModes.length !== 2 ||
  !colourModes.includes('Light') ||
  !colourModes.includes('Dark')
) {
  fail(
    `Collection "${COLLECTION.colours}" must have exactly the modes Light and Dark; found ${colourModes.join(
      ', ',
    )}.`,
  );
}

const lightLines = [];
const darkLines = [];

for (const variable of colourEntry.variableMap.values()) {
  for (const mode of ['Light', 'Dark']) {
    const where = `${COLLECTION.colours}/${variable.name} [${mode}]`;
    const value = variable.values[mode];
    const alias = aliasToCss(value, where);

    let cssValue;
    if (alias) {
      cssValue = alias;
    } else {
      cssValue = expectHex(value, where);
      warn(
        `${where} is a raw colour, not an alias; it was written as a literal in roles.css.`,
      );
    }

    const line = `  --color-${dash(variable.name)}: ${cssValue};`;
    if (mode === 'Light') lightLines.push(line);
    else darkLines.push(line);
  }
}

/* ------------------------------------------------------------------ */
/* Spacing roles                                                      */
/* ------------------------------------------------------------------ */

const spacingEntry = getCollection(COLLECTION.spacing);
const spacingModes = spacingEntry.definition.modes;

if (!spacingModes.includes('Compact')) {
  fail(
    `Collection "${COLLECTION.spacing}" has no Compact mode; found ${spacingModes.join(
      ', ',
    )}.`,
  );
}

const breakpointVariable = spacingEntry.variableMap.get('breakpoint/min-width');
if (!breakpointVariable) {
  fail('spacing roles is missing breakpoint/min-width.');
}

const modeMinWidths = new Map();
for (const mode of spacingModes) {
  const value = breakpointVariable.values[mode];
  if (value === undefined) {
    fail(`breakpoint/min-width has no value for mode "${mode}".`);
  }
  modeMinWidths.set(
    mode,
    expectNumber(value, `spacing roles/breakpoint/min-width [${mode}]`),
  );
}

function breakpointComment(mode) {
  const parts = [];
  for (const name of [
    'breakpoint/min-width',
    'breakpoint/max-width',
    'breakpoint/design-width',
  ]) {
    const variable = spacingEntry.variableMap.get(name);
    if (!variable) continue;
    const value = variable.values[mode];
    if (value === undefined) continue;
    const number = expectNumber(value, `spacing roles/${name} [${mode}]`);
    parts.push(`${name.replace('breakpoint/', '')}: ${number}px`);
  }
  return parts.join(', ');
}

function spacingLines(mode) {
  const lines = [];
  for (const variable of spacingEntry.variableMap.values()) {
    if (variable.name.startsWith('breakpoint/')) continue;

    const where = `${COLLECTION.spacing}/${variable.name} [${mode}]`;
    const value = variable.values[mode];
    const alias = aliasToCss(value, where);

    let cssValue;
    if (alias) {
      cssValue = alias;
    } else {
      const number = expectNumber(value, where);
      /* Columns and panes are counts; the other raw spacing values are px. */
      const unit =
        variable.name === 'layout/columns' || variable.name === 'layout/panes'
          ? ''
          : 'px';
      cssValue = `${number}${unit}`;
    }

    lines.push(`  --spacing-${dash(variable.name)}: ${cssValue};`);
  }
  return lines;
}

const orderedSpacingModes = [
  'Compact',
  ...spacingModes
    .filter((mode) => mode !== 'Compact')
    .sort((a, b) => modeMinWidths.get(a) - modeMinWidths.get(b)),
];
const spacingLinesByMode = new Map();
for (const mode of orderedSpacingModes) {
  spacingLinesByMode.set(mode, spacingLines(mode));
}

const spacingWritten = [...spacingLinesByMode.values()].reduce(
  (total, lines) => total + lines.length,
  0,
);
const breakpointVariableCount = [...spacingEntry.variableMap.keys()].filter(
  (name) => name.startsWith('breakpoint/'),
).length;

/* ------------------------------------------------------------------ */
/* Shape roles                                                        */
/* ------------------------------------------------------------------ */

const { entry: shapeEntry, mode: shapeMode } = getSingleMode(
  COLLECTION.shape,
);

const shapeLines = [];
for (const variable of shapeEntry.variableMap.values()) {
  const where = `${COLLECTION.shape}/${variable.name} [${shapeMode}]`;
  const name = cssVariableName(COLLECTION.shape, variable.name);
  if (!name) {
    fail(
      `${where}: unsupported shape-role name; expected radius/* or border/width/*.`,
    );
  }

  const value = variable.values[shapeMode];
  const alias = aliasToCss(value, where);

  let cssValue;
  if (alias) {
    cssValue = alias;
  } else {
    cssValue = `${expectNumber(value, where)}px`;
  }

  shapeLines.push(`  ${name}: ${cssValue};`);
}

/* ------------------------------------------------------------------ */
/* Shadows (from effectStyles, not from the per-variable tokens)      */
/* ------------------------------------------------------------------ */

const shadowEntry = getCollection(COLLECTION.shadow);
const expectedShadows = ['shadow/hard', 'shadow/medium', 'shadow/soft'];
const effectStylesByName = new Map();

for (const style of data.effectStyles) {
  if (effectStylesByName.has(style.name)) {
    fail(`Duplicate effect style "${style.name}".`);
  }
  effectStylesByName.set(style.name, style);
  if (!expectedShadows.includes(style.name)) {
    warn(
      `Effect style "${style.name}" was not converted; only shadow/hard, shadow/medium and shadow/soft are supported.`,
    );
  }
}

const shadowLines = [];
for (const styleName of expectedShadows) {
  const style = effectStylesByName.get(styleName);
  if (!style) {
    fail(`Missing effect style "${styleName}".`);
  }
  if (style.type !== 'DROP_SHADOW') {
    fail(
      `Effect style "${styleName}" has type ${JSON.stringify(
        style.type,
      )}; expected DROP_SHADOW.`,
    );
  }

  const where = `effectStyles/${styleName}`;
  const x = expectNumber(style.x, `${where}.x`);
  const y = expectNumber(style.y, `${where}.y`);
  const blur = expectNumber(style.blur, `${where}.blur`);
  const spread = expectNumber(style.spread, `${where}.spread`);
  const opacity = expectNumber(style.opacity, `${where}.opacity`);
  if (opacity < 0 || opacity > 1) {
    warn(`${where}.opacity is ${opacity}; expected a value from 0 to 1.`);
  }

  const { r, g, b } = hexToRgb(style.color, `${where}.color`);
  const name = `--shadow-${dash(styleName.slice('shadow/'.length))}`;
  shadowLines.push(
    `  ${name}: ${x}px ${y}px ${blur}px ${spread}px rgb(${r} ${g} ${b} / ${opacity});`,
  );
}

/* ------------------------------------------------------------------ */
/* Typography                                                         */
/* ------------------------------------------------------------------ */

const { entry: typographyEntry, mode: typographyMode } = getSingleMode(
  COLLECTION.typography,
);

const typographyLines = [];
const typeClasses = [];
const usedTypographyVariables = new Set();
const seenTextStyles = new Set();

for (const textStyle of data.textStyles) {
  const styleName = textStyle.name.startsWith('type/')
    ? textStyle.name.slice('type/'.length)
    : textStyle.name;

  if (seenTextStyles.has(styleName)) {
    fail(`Duplicate text style "${textStyle.name}".`);
  }
  seenTextStyles.add(styleName);

  function typographyValue(suffix) {
    const name = `${styleName}/${suffix}`;
    const variable = typographyEntry.variableMap.get(name);
    if (!variable) {
      fail(
        `Missing typography variable "${name}" required by text style "${textStyle.name}".`,
      );
    }
    if (variable.type !== 'FLOAT') {
      fail(
        `Typography variable "${name}" has type ${JSON.stringify(
          variable.type,
        )}; expected FLOAT.`,
      );
    }
    const value = variable.values[typographyMode];
    if (value === undefined) {
      fail(
        `Typography variable "${name}" has no value for mode "${typographyMode}".`,
      );
    }
    usedTypographyVariables.add(name);
    return expectNumber(value, `typography/${name} [${typographyMode}]`);
  }

  const weight = typographyValue('weight');
  const size = typographyValue('size');
  const lineHeight = typographyValue('line-height');
  const letterSpacing = typographyValue('letter-spacing');

  if (
    typeof textStyle.fontFamily !== 'string' ||
    textStyle.fontFamily.trim() === ''
  ) {
    fail(`Text style "${textStyle.name}" has no fontFamily.`);
  }

  if (
    typeof textStyle.fontSize === 'number' &&
    textStyle.fontSize !== size
  ) {
    warn(
      `Text style "${textStyle.name}".fontSize is ${textStyle.fontSize}, but typography/${styleName}/size is ${size}; the variable wins.`,
    );
  }
  if (
    typeof textStyle.lineHeightPx === 'number' &&
    textStyle.lineHeightPx !== lineHeight
  ) {
    warn(
      `Text style "${textStyle.name}".lineHeightPx is ${textStyle.lineHeightPx}, but typography/${styleName}/line-height is ${lineHeight}; the variable wins.`,
    );
  }
  if (
    typeof textStyle.letterSpacingPx === 'number' &&
    textStyle.letterSpacingPx !== letterSpacing
  ) {
    warn(
      `Text style "${textStyle.name}".letterSpacingPx is ${textStyle.letterSpacingPx}, but typography/${styleName}/letter-spacing is ${letterSpacing}; the variable wins.`,
    );
  }

  const family = `${JSON.stringify(
    textStyle.fontFamily,
  )}, "Noto Sans", system-ui, sans-serif`;
  const prefix = `--type-${dash(styleName)}`;

  typographyLines.push(
    `  ${prefix}-family: ${family};`,
    `  ${prefix}-weight: ${weight};`,
    `  ${prefix}-size: ${size}px;`,
    `  ${prefix}-line-height: ${lineHeight}px;`,
    `  ${prefix}-letter-spacing: ${letterSpacing}px;`,
  );

  typeClasses.push(
    [
      `.type-${dash(styleName)} {`,
      `  font-family: var(${prefix}-family);`,
      `  font-weight: var(${prefix}-weight);`,
      `  font-size: var(${prefix}-size);`,
      `  line-height: var(${prefix}-line-height);`,
      `  letter-spacing: var(${prefix}-letter-spacing);`,
      '}',
    ].join('\n'),
  );
}

for (const variable of typographyEntry.variableMap.values()) {
  if (usedTypographyVariables.has(variable.name)) continue;
  if (!variable.name.endsWith('/line-height-multiplier')) {
    warn(
      `typography/${variable.name} is not referenced by any text style and was not emitted.`,
    );
  }
}

/* ------------------------------------------------------------------ */
/* Assemble roles.css and index.css                                   */
/* ------------------------------------------------------------------ */

const roles = [HEADER, ''];

roles.push(':root {', '  /* colour roles (Light) */', ...lightLines, '}');
roles.push('');

roles.push(
  '[data-theme="dark"] {',
  '  /* colour roles (Dark) */',
  ...darkLines,
  '}',
);
roles.push('');

roles.push(
  '@media (prefers-color-scheme: dark) {',
  '  :root:not([data-theme="light"]) {',
  '    /* colour roles (Dark) */',
  ...darkLines.map((line) => `  ${line}`),
  '  }',
  '}',
);
roles.push('');

for (const mode of orderedSpacingModes) {
  const comment = `/* spacing roles (${mode}) - ${breakpointComment(mode)} */`;
  const lines = spacingLinesByMode.get(mode);

  if (mode === 'Compact') {
    roles.push(comment, ':root {', ...lines, '}');
  } else {
    const minWidth = modeMinWidths.get(mode);
    roles.push(
      comment,
      `@media (min-width: ${minWidth}px) {`,
      '  :root {',
      ...lines.map((line) => `  ${line}`),
      '  }',
      '}',
    );
  }
  roles.push('');
}

roles.push('/* shape roles */', ':root {', ...shapeLines, '}');
roles.push('');

roles.push(
  '/* shadow roles (values from effectStyles, converted to box-shadow) */',
  ':root {',
  ...shadowLines,
  '}',
);
roles.push('');

roles.push('/* typography */', ':root {', ...typographyLines, '}');
roles.push('');
roles.push('/* typography utility classes */');
for (const block of typeClasses) {
  roles.push(block);
  roles.push('');
}

const rolesCss = `${roles.join('\n').replace(/\n+$/, '')}\n`;

const indexCss = `${HEADER}\n\n@import "primitives.css";\n@import "roles.css";\n`;

/* ------------------------------------------------------------------ */
/* Write output and print the counts                                  */
/* ------------------------------------------------------------------ */

fs.mkdirSync(OUTPUT_DIR, { recursive: true });
fs.writeFileSync(path.join(OUTPUT_DIR, 'primitives.css'), primitivesCss);
fs.writeFileSync(path.join(OUTPUT_DIR, 'roles.css'), rolesCss);
fs.writeFileSync(path.join(OUTPUT_DIR, 'index.css'), indexCss);

noteSkipped(
  `spacing roles/${[
    'breakpoint/min-width',
    'breakpoint/max-width',
    'breakpoint/design-width',
  ].join(', spacing roles/')} (breakpoint variables; their numbers are in the comments above each spacing block)`,
);
noteSkipped(
  `${COLLECTION.shadow}: all ${shadowEntry.variableMap.size} per-variable tokens (the output uses ${expectedShadows.length} effectStyles instead)`,
);

const multiplierCount = [...typographyEntry.variableMap.keys()].filter((name) =>
  name.endsWith('/line-height-multiplier'),
).length;
if (multiplierCount > 0) {
  noteSkipped(
    `typography: ${multiplierCount} line-height-multiplier variables (the px line height is emitted instead)`,
  );
}
noteSkipped(
  `textStyles.fontStyle labels (${[
    ...new Set(data.textStyles.map((style) => style.fontStyle).filter(Boolean)),
  ].join(', ')}) (weight comes from the typography collection)`,
);

const stats = [
  {
    name: COLLECTION.primitives,
    read: primitivesEntry.variableMap.size,
    written: primitiveLines.length,
    note: 'one :root block',
  },
  {
    name: COLLECTION.colours,
    read: colourEntry.variableMap.size,
    written: lightLines.length + darkLines.length * 2,
    note: `Light ${lightLines.length}; Dark ${darkLines.length} (written twice)`,
  },
  {
    name: COLLECTION.spacing,
    read: spacingEntry.variableMap.size,
    written: spacingWritten,
    note: `${spacingWritten / spacingModes.length} per mode x ${
      spacingModes.length
    }; ${breakpointVariableCount * spacingModes.length} breakpoint props skipped`,
  },
  {
    name: COLLECTION.typography,
    read: typographyEntry.variableMap.size,
    written: typographyLines.length,
    note: `${data.textStyles.length} text styles x 5; ${multiplierCount} multipliers skipped; family from textStyles`,
  },
  {
    name: COLLECTION.shape,
    read: shapeEntry.variableMap.size,
    written: shapeLines.length,
    note: '',
  },
  {
    name: COLLECTION.shadow,
    read: shadowEntry.variableMap.size,
    written: shadowLines.length,
    note: `per-variable output skipped; ${shadowLines.length} effectStyles emitted`,
  },
];

const totalRead = stats.reduce((sum, row) => sum + row.read, 0);
